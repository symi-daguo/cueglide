import Foundation

/// 性能压测用的长文本，只在调试场景通过启动参数注入，不参与正式界面。
enum SampleText {

    /// 约一万字，用来验证长稿的排版测量、滚动与高亮性能。
    static let long: String = {
        let paragraph = """
        提词器最容易被忽略的不是字号，而是阅读线的位置。字号再大，如果文字离镜头太远，观众看到的仍然是你在低头念稿。把阅读线压到屏幕上方靠近前置摄像头的位置，视线偏移会小很多，这是所有提词器产品都在做但很少做对的一件事。

        第二件事是滚动的手感。匀速是最难做好的一种，因为人的语速天然不匀速，读得顺的时候快，遇到生僻词会慢下来。所以除了恒速，还需要能按字数配速、按总时长倒计时，以及最理想的跟读模式。

        第三件事是位置记忆。换字号、换行距、折叠屏展开，这些都会触发重新排版，如果位置按像素记就会丢，必须按词记。这一点在长稿上尤其明显。

        第四件事是性能。一万字的稿子如果每次高亮都重建整段富文本，滚动必然掉帧。正确做法是只改变化的那几个词的属性区间，其余部分原样不动。

        """
        return String(repeating: paragraph, count: 40)
    }()
}
